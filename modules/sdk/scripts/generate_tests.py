#!/usr/bin/env python3
"""Generate PCDOGS C/CMake test surfaces from Python blueprints."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.dont_write_bytecode = True

from codegen import c_mask, c_sig, write_or_check
from generate_headers import load_blueprint, split_row_unstable_rows

try:
    from mako.template import Template
except ImportError as exc:
    raise SystemExit(
        "generate_tests.py requires Mako; install it or enter the Nix dev shell."
    ) from exc

ENUM_PREFIXES = {
    "required": "DTTR_TEST_PCDOGS_REQUIRED",
    "cc": "DTTR_PCDOGS_CC",
    "hook": "DTTR_PCDOGS_HOOK",
}


def prefixed_enum(kind: str, value: object) -> str:
    return f"{ENUM_PREFIXES[kind]}_{str(value).upper()}"


def required_enum(required: object) -> str:
    return prefixed_enum("required", required)


def cc_enum(cc: object) -> str:
    return prefixed_enum("cc", cc)


def hook_enum(kind: object) -> str:
    return prefixed_enum("hook", kind)


def typed_params(fn: object) -> list[object]:
    """Return typed parameters for ABI checks against recovered signatures."""

    return list(fn.typed.params if fn.typed else [])


def function_cc(fn: object) -> object:
    return getattr(fn, "cc", None) or fn.calling_convention


def abi_stack_bytes(fn: object) -> int:
    """Compute expected stack cleanup bytes from reverse-engineered calling convention metadata."""

    params = typed_params(fn)
    stack_bytes = len(params) * 4

    if str(function_cc(fn)) == "fastcall":
        stack_bytes = max(0, stack_bytes - min(2, len(params)) * 4)

    return stack_bytes


ROWS_TEMPLATE = Template(
    """// Generated by generate_tests.py.

% for symbol, blueprint in blueprints:
static const blueprint_signature ${symbol}_SIGNATURES[] = {
% for sig in blueprint.signatures:
\t{"${sig.name}", (const uint8_t *)${c_sig(sig.pattern)}, ${c_mask(sig.pattern)}, ${required_enum(sig.required)}},
% endfor
};

static const blueprint_function ${symbol}_FUNCTIONS[] = {
% for fn in blueprint.functions:
<% patch_size = fn.hook.patch_size %>\
<% entry_patch_size = fn.hook.entry_patch_size or patch_size %>\
\t{"${fn.name}", (const uint8_t *)${c_sig(fn.pattern)}, ${c_mask(fn.pattern)}, ${required_enum(fn.required)}, ${int(fn.match_offset)}, ${cc_enum(function_cc(fn))}, ${hook_enum(fn.hook.kind)}, ${int(patch_size)}u, ${int(entry_patch_size)}u, ${len(typed_params(fn))}u, ${abi_stack_bytes(fn)}u},
% endfor
};

% endfor
""".lstrip(),
    strict_undefined=True,
)


def render(template: Template, **kwargs: object) -> str:
    """Render one generated test artifact with stable newline handling for CMake checks."""

    text = template.render_unicode(
        c_mask=c_mask,
        c_sig=c_sig,
        required_enum=required_enum,
        cc_enum=cc_enum,
        hook_enum=hook_enum,
        function_cc=function_cc,
        typed_params=typed_params,
        abi_stack_bytes=abi_stack_bytes,
        int=int,
        len=len,
        **kwargs,
    )
    return text if text.endswith("\n") else f"{text}\n"


def load_blueprint_surfaces(path: Path) -> list[tuple[str, object]]:

    stable, unstable = split_row_unstable_rows(load_blueprint(path))
    return [
        ("DTTR_PCDOGS", stable),
        ("DTTR_PCDOGS_UNSTABLE", unstable),
    ]


def main() -> int:
    """Generate blueprint-driven C and CMake fixtures used by the SDK signature tests."""

    parser = argparse.ArgumentParser()
    parser.add_argument("--rows-output", required=True, type=Path)
    parser.add_argument("blueprint", type=Path)
    args = parser.parse_args()

    blueprints = load_blueprint_surfaces(args.blueprint)
    write_or_check(args.rows_output, render(ROWS_TEMPLATE, blueprints=blueprints))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
