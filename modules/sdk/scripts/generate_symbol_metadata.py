def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate PCDOGS SDK SymbolManifest JSON from Python blueprints.",
    )
    parser.add_argument("blueprint", type=Path, nargs="?", default=None)
    parser.add_argument("--metadata-dir", type=Path, default=None)
    parser.add_argument("--sdk-version", default=None)
    parser.add_argument("--sdk-abi-version", default=None)
    parser.add_argument("--check", action="store_true", help="fail if output is stale")
    parser.add_argument(
        "--function-call-xrefs",
        action="append",
        type=Path,
        default=[],
        help="JSON call xrefs generated by generate_function_call_xrefs.py",
    )
    parser.add_argument(
        "--symbol-addresses",
        action="append",
        type=Path,
        default=[],
        help="JSON symbol addresses generated by resolve_symbol_addresses.py",
    )
    return parser.parse_args()


def sdk_root() -> Path:
    return Path(__file__).resolve().parent.parent


def repo_root() -> Path:
    return sdk_root().parent.parent


def parse_sdk_abi_version() -> int:
    text = (sdk_root() / "include/dttr_versions.h.in").read_text()
    match = re.search(r"^#define\s+DTTR_SDK_ABI_VERSION\s+(\d+)u?", text, re.MULTILINE)

    if match is None:
        raise ValueError("dttr_versions.h.in missing DTTR_SDK_ABI_VERSION")

    return int(match.group(1))


def git_commit() -> str | None:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=repo_root(),
            text=True,
            capture_output=True,
            check=True,
        )

    except (FileNotFoundError, subprocess.CalledProcessError):
        return None

    commit = result.stdout.strip()
    return commit or None


def load_authored_blueprint(path: Path) -> object:
    module = load_python_module(path, "manifest_blueprint_source")
    blueprint = getattr(module, "BLUEPRINT", None)

    if blueprint is None:
        raise ValueError(f"blueprint module does not define BLUEPRINT: {path}")

    return blueprint


def supported_builds(value: object) -> list[str]:
    bits = build_mask_bits(value)
    return [name for name in SUPPORTED_BUILDS if bits & BUILD_MASK_BITS[name]]


def function_accessor(name: object) -> str:
    return f"DTTR_PCDOGS_F_{c_public_token(name)}"


def data_accessor(name: object) -> str:
    return f"DTTR_PCDOGS_D_{c_public_token(name)}"


UNDOCUMENTED_TEXT = "Not yet documented."


def doc_text(value: object | None) -> str | None:
    if value is None:
        return None
    text = " ".join(str(value).split())
    if not text or text == UNDOCUMENTED_TEXT:
        return None
    return text


def model_row(row: object, *, exclude: set[str] | None = None) -> dict[str, object]:
    if hasattr(row, "model_dump"):
        return row.model_dump(
            mode="json",
            by_alias=True,
            exclude=exclude or set(),
            exclude_none=False,
        )
    raise TypeError(f"manifest row does not support model_dump: {row!r}")


def without_name(row: object) -> dict[str, object]:
    return model_row(row, exclude={"name"})


def param_metadata(param: object) -> ManifestParam:
    if pair := param_type_name(param):
        type_, name = pair
        return ManifestParam(
            name=str(name),
            type=c_type(type_),
            docs=doc_text(getattr(param, "doc", None)),
        )
    return ManifestParam(name=arg_name(param), type=c_type(param))


def function_resolver(row: object) -> FunctionResolver:
    return FunctionResolver(
        pattern=row.pattern,
        match_offset=int(row.match_offset),
    )


def computed_function(row: object) -> ComputedFunction:
    typed = row.typed

    if typed is None:
        raise ValueError(f"function is missing typed metadata: {row.name}")

    return ComputedFunction(
        id=int(row.public_index),
        symbol_index=int(row.index),
        name=str(row.name),
        accessor=function_accessor(row.name),
        prototype=FunctionPrototype(
            return_type=c_type(typed.return_type),
            params=[param_metadata(param) for param in typed.params],
            calling_convention=typed.abi,
            abi_status=row.abi_status,
        ),
        builds=supported_builds(row.supported_builds),
        callable=bool(typed.callable),
        resolver=function_resolver(row),
        hook_kind=typed.hook_kind,
        patch_sizes=PatchSizes(
            patch_size=int(row.hook.patch_size),
            entry_patch_size=int(row.hook.entry_patch_size),
        ),
        docs=doc_text(symbol_doc(SymbolDocKind.FUNCTION, row)),
        unstable=bool(row.unstable),
        sdk_id=f"DTTR_PCDOGS_FUNCTION_{row.symbol_id}",
        symbol_id=f"DTTR_PCDOGS_SYMBOL_FUNCTION_ID_{row.symbol_id}",
    )


def computed_data_resolver(row: object) -> DataResolver | None:
    typed = row.typed

    if typed is None:
        return None

    return DataResolver(
        kind=typed.resolver,
        ref_function=str(typed.ref_function),
        instr_offset=int(typed.instr_off),
        addr_offset=int(typed.addr_off),
        indirections=int(typed.indirections),
    )


def computed_data(row: object) -> ComputedDataSymbol:
    policy = data_write_policy(row).removeprefix("DTTR_PCDOGS_WRITE_POLICY_").lower()
    return ComputedDataSymbol(
        id=int(row.public_index),
        symbol_index=int(row.public_index),
        name=str(row.name),
        accessor=data_accessor(row.name),
        type=c_type(row.typed.type) if row.typed else None,
        builds=supported_builds(row.supported_builds),
        resolver=computed_data_resolver(row),
        write_policy=policy,
        docs=doc_text(symbol_doc(SymbolDocKind.GLOBAL, row)),
        unstable=bool(row.unstable),
        sdk_id=f"DTTR_PCDOGS_DATA_{row.symbol_id}",
        symbol_id=f"DTTR_PCDOGS_SYMBOL_DATA_ID_{row.symbol_id}",
    )


def computed_type(row: object) -> ComputedType:
    kind = type_row_kind(row).value
    return ComputedType(
        name=str(row.name),
        kind=kind,
        sdk_name=pcdogs_type_name(row.name),
        size=getattr(row, "size", None),
        docs=doc_text(row_doc(row)),
        unstable=bool(getattr(row, "unstable", False)),
    )


def computed_signature(row: object) -> ComputedSignature:
    return ComputedSignature(
        name=str(row.name),
        pattern=str(row.pattern),
        builds=supported_builds(row.required),
        docs=doc_text(getattr(row, "doc", None)),
        unstable=bool(row.unstable),
    )


